// Writes Themes/Icons.axaml from the path data of @mui/icons-material (22 section 4). Node 20, no dependencies.
//   node tools/icons/build-icons.mjs <path to the @mui/icons-material folder> [icons.json] [output.axaml]
// Every icon becomes a StreamGeometry resource "Icon.<Name>" in the package's 24x24 design box.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const [pkgArg, listArg, outArg] = process.argv.slice(2);
if (!pkgArg) {
  console.error('usage: node build-icons.mjs <@mui/icons-material folder> [icons.json] [output.axaml]');
  process.exit(2);
}
const pkgDir = resolve(pkgArg);
const listFile = resolve(listArg ?? join(here, 'icons.json'));
const outFile = resolve(outArg ?? join(here, '..', '..', 'src', 'Fadenstack.UI.Avalonia', 'Themes', 'Icons.axaml'));

const list = JSON.parse(readFileSync(listFile, 'utf8'));
const version = JSON.parse(readFileSync(join(pkgDir, 'package.json'), 'utf8')).version;
if (version !== list.version) {
  console.error(`icons.json pins ${list.package} ${list.version}, but the folder holds ${version}. Update the pin on purpose.`);
  process.exit(1);
}

const names = list.icons;
const dup = names.filter((n, i) => names.indexOf(n) !== i);
if (dup.length) { console.error(`duplicate names: ${dup.join(', ')}`); process.exit(1); }

const rows = [];
for (const name of names) {
  const src = readFileSync(join(pkgDir, 'esm', `${name}.js`), 'utf8');
  if (/opacity/.test(src)) throw new Error(`${name}: has an opacity layer (two-tone); not supported`);
  const paths = [...src.matchAll(/\bd:\s*"([^"]+)"/g)].map((m) => m[1]);
  if (paths.length === 0) throw new Error(`${name}: no path data found`);
  // Several paths of one icon are joined into one geometry. A relative "m" opening a later path would continue from the
  // previous path's end, so it is made absolute (a path's first moveto is absolute anyway).
  const data = paths.map((p, i) => (i > 0 && p.startsWith('m') ? 'M' + p.slice(1) : p)).join(' ');
  rows.push(`    <StreamGeometry x:Key="Icon.${name}">${data}</StreamGeometry>`);
}

const xml = `<ResourceDictionary xmlns="https://github.com/avaloniaui"
                    xmlns:x="http://schemas.microsoft.com/winfx/2006/xaml">
    <!--
        GENERATED by tools/icons/build-icons.mjs from ${list.package} ${version}; do not edit. Add an icon in
        tools/icons/icons.json and run the script (tools/icons/README.md). Each icon is a StreamGeometry in the package's
        24x24 design box; FsIcon scales that box, not the path's bounds. Licences: MIT (MUI), Apache-2.0 (Google Material
        Icons), see THIRD-PARTY-NOTICES.
    -->
${rows.join('\n')}
</ResourceDictionary>
`;
writeFileSync(outFile, xml.replace(/\r?\n/g, '\n'), 'utf8');
console.log(`${names.length} icons from ${list.package} ${version} -> ${outFile}`);
